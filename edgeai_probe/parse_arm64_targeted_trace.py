#!/usr/bin/env python3
"""Summarize genuine QEMU ARM64 single-step register snapshots in one function.

A QEMU -d cpu,in_asm -singlestep trace is NOT a reconstruction or an opcode
interpreter: these registers are generated by executing the original ELF.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re

# Accept QEMU user-mode AArch64 CPU log variants with whitespace around "=".
REGS=re.compile(r'(?<![A-Za-z0-9_])(PC|SP|X(?:0[0-9]|[12][0-9]|30))\s*=\s*([0-9a-fA-F]{1,16})\b')
PSTATE=re.compile(r'\bPSTATE\s*=\s*([0-9a-fA-F]{1,16})\b')
RESULT=re.compile(r'^EDGEAI_MACHINE_RESULT case=(\d+) return=(\d+) board_sha_fnv64=([0-9a-f]{16})$')
INPUT=re.compile(r'^EDGEAI_MACHINE_DEBUG case=(\d+) entry=0x([0-9a-f]{16}) board=\[([\d,]+)\]$')


def parse_trace(trace, entry, end, max_records=2048):
    if not 0 < end-entry <= 4096 or entry&3 or end&3:
        raise ValueError('invalid bounded ARM64 function interval')
    text=Path(trace).read_text(errors='replace')
    snapshots=[]
    current=None
    for line in text.splitlines():
        registers=dict((reg,int(val,16)) for reg,val in REGS.findall(line))
        if 'PC' in registers:
            if current is not None and entry<=current['pc']<end:
                snapshots.append(current)
            current={'pc':registers.pop('PC'),'regs':{}}
        if current is not None:
            current['regs'].update(registers)
            match=PSTATE.search(line)
            if match:current['pstate']=int(match[1],16)
    if current is not None and entry<=current['pc']<end:
        snapshots.append(current)
    if not snapshots:
        raise ValueError('No QEMU CPU snapshots within intended code range')
    if len(snapshots)>max_records:
        raise ValueError('ARM64 trace exceeded bounded instruction budget')
    if snapshots[0]['pc']!=entry:
        raise ValueError('Target trace did not start at selected entry')
    branches=[]
    for ix,prev in enumerate(snapshots[:-1]):
        now=snapshots[ix+1]
        if now['pc']!=prev['pc']+4:
            branches.append({'at':hex(prev['pc']),'next':hex(now['pc']),
                             'type':'intra_function_nonsequential_PC'})
    # We purposely retain registers as hexadecimal strings for portability.
    converted=[]
    for x in snapshots:
        item={'pc':hex(x['pc']),'regs':{k:hex(v) for k,v in sorted(x['regs'].items())}}
        if 'pstate' in x:item['pstate']=hex(x['pstate'])
        converted.append(item)
    return {'function_start':hex(entry),'function_end_exclusive':hex(end),
        'cpu_snapshot_count':len(converted),'branch_change_count':len(branches),
        'branches':branches,
        'sample_entry_registers':converted[0],
        'sample_last_registers':converted[-1],
        'snapshot_sequence':converted,
        'qemu_raw_trace_sha256':hashlib.sha256(Path(trace).read_bytes()).hexdigest()}


def verify_debug_stdout(output, case, entry):
    lines=Path(output).read_text().splitlines()
    if len(lines)!=2:
        raise ValueError('targeted original ELF hook did not produce two records')
    a=INPUT.fullmatch(lines[0]);b=RESULT.fullmatch(lines[1])
    if not a or not b or int(a[1])!=case or int(b[1])!=case or int(a[2],16)!=entry:
        raise ValueError('original ELF input and output lines mismatch')
    board=list(map(int,a[3].split(',')))
    if len(board)!=16:
        raise ValueError('invalid board length')
    return {'case':case,'input_board':board,'actual_original_return':int(b[2]),
            'board_after_fnv64':b[3]}


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--trace',type=Path,required=True)
    p.add_argument('--stdout',type=Path,required=True)
    p.add_argument('--entry',type=lambda x:int(x,0),required=True)
    p.add_argument('--stop',type=lambda x:int(x,0),required=True)
    p.add_argument('--case',type=int,required=True)
    p.add_argument('--output',type=Path,required=True)
    args=p.parse_args()
    state=parse_trace(args.trace,args.entry,args.stop)
    state['original_machine_io']=verify_debug_stdout(args.stdout,args.case,args.entry)
    state['executed_original_elf_machine_code']=True
    state['used_source_or_game_symbols']=False
    state['trace_kind']='QEMU user-mode AArch64 CPU single-step snapshots'
    args.output.parent.mkdir(parents=True,exist_ok=True)
    args.output.write_text(json.dumps(state,indent=2)+'\n')
    print(json.dumps({key:state[key] for key in ('function_start','cpu_snapshot_count','branch_change_count','original_machine_io')},indent=2))


if __name__=='__main__':main()
