#!/usr/bin/env python3
"""Create source-verified original Unity m_buildChilds icon atlases and C++ data.

Reads EdgeAI's cfg.BuildPart.oc decode and original buildpart Sprite manifest.
Uses exact bundle + exact sprite name + exact PathID. No approximate icon
matching and no manual menu order. The original prefab has 11 Toggle slots.
"""
import argparse
import json
from pathlib import Path
from PIL import Image

TILE = 120
SLOTS = 11
TYPES = (2,3,4,6,7,8)

def cpp_string(s):
    return json.dumps(s,ensure_ascii=True)

def export(report,sprites,folder,out):
    out.mkdir(parents=True,exist_ok=True)
    mapping={}
    summary={}
    items=[]
    for typ in TYPES:
        group=next((v for v in report["groups"].values()
                    if v["type_id"]==typ),None)
        if group is None:raise ValueError("No config group "+str(typ))
        records=group["items"]
        if not records or len(records)>SLOTS:
            raise ValueError("Original prefab has 11 slots, category "+str(typ)+
                             " has "+str(len(records))+" source entries")
        atlas=Image.new("RGBA",(TILE*SLOTS,TILE),(0,0,0,0))
        rows=[]
        for index,entry in enumerate(records):
            refs=entry.get("verified_icon_candidates",[])
            if len(refs)!=1:
                raise ValueError("Unverified source icon: BuildPart "+
                                 str(entry["id"])+" "+entry["icon"]+" "+
                                 str(refs))
            ref=refs[0]
            path=folder/ref["file"]
            if not path.is_file():raise FileNotFoundError(path)
            with Image.open(path) as original:
                image=original.convert("RGBA")
                if image.size!=(TILE,TILE):
                    raise ValueError("Unexpected Unity sprite size "+str(image.size))
                atlas.alpha_composite(image,(index*TILE,0))
            rows.append({
                "index":index,
                "id":entry["id"],"type":typ,
                "name":entry["name"],"icon":entry["icon"],
                "once_angle":entry["OnceAngle"],"model":entry["model"],
                "material":entry["materialInfo"],
                "path_id":ref["path_id"],"bundle":ref["bundle"]
            })
            items.append(rows[-1])
        path="hud_original_build_items_type_"+str(typ)+".png"
        atlas.save(out/path,optimize=True)
        mapping[str(typ)]=rows
        summary[str(typ)]={"count":len(rows),"atlas":path}
        print("EDGEAI_UNITY_EXACT_SUBMENU_ATLAS",typ,len(rows),path,flush=True)
    result={"schema":"edgeai.unity-submenu-atlas.v1",
            "source_buildpart_sha256":report["sha256"],
            "source_level1_only":True,
            "unity_toggle_slots":SLOTS,
            "category_items":mapping,
            "atlases":summary,
            "limitations":["These are genuine original sprites with exact provenance.",
                "Runtime selected highlight and Unity font/layout are separate.",
                "Does not prove original model meshes/placement were reconstructed."]}
    (out/"buildpart_submenu_manifest.json").write_text(
        json.dumps(result,indent=2,ensure_ascii=False)+"\n")
    lines=["#pragma once",
           "// GENERATED by EdgeAI from original XAPK cfg.BuildPart.oc.",
           "// Do not edit or infer missing source items.",
           "namespace LIOS_SOURCE_BUILD {",
           "struct Item {int id,type,index,onceAngle;const char* icon;const char* model;};",
           "static constexpr Item Items[]={"]
    for r in items:
        angle=r["once_angle"] if r["once_angle"] is not None else -1
        lines.append("  {%d,%d,%d,%d,%s,%s}," % (
            r["id"],r["type"],r["index"],angle,
            cpp_string(r["icon"]),cpp_string(r["model"])))
    lines.extend(["};",
                  "inline const Item* find(int typ,int slot){",
                  "  for(const auto &x:Items)if(x.type==typ&&x.index==slot)return &x;",
                  "  return nullptr;",
                  "}",
                  "inline int count(int typ){int n=0;for(const auto &x:Items)"
                  "if(x.type==typ)++n;return n;}",
                  "} // namespace LIOS_SOURCE_BUILD"])
    (out/"original_buildpart_v7.hpp").write_text("\n".join(lines)+"\n")
    return result

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument("--source",type=Path,required=True)
    p.add_argument("--sprites",type=Path,required=True)
    p.add_argument("--sprite-directory",type=Path,required=True)
    p.add_argument("--output",type=Path,required=True)
    a=p.parse_args()
    report=json.loads(a.source.read_text())
    icons=json.loads(a.sprites.read_text())
    export(report,icons,a.sprite_directory,a.output)
if __name__=="__main__":main()
